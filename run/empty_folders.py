def search_files_to_delete(root):
    paths_to_files = []

    for root_folder, sub_folder, files in os.walk(root):
        if re.search('c=', root_folder) and ('data.csv' in files or 'data.txt' in files):
            paths_to_files.append(os.path.join(root_folder+r'\\'+files[0]))
    return paths_to_files
